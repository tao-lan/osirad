test_that("pyradiomics_features() uses the R voxels and SUV", {
  python = Sys.getenv("OSIRAD_PYTHON")
  skip_if(python == "", "OSIRAD_PYTHON not set")
  skip_if_not_installed("reticulate")
  xml_file = system.file("extdata", "phantom", "ROI.xml", package = "osirad")
  pet_dir = system.file("extdata", "phantom", "pet", package = "osirad")
  x = extract_roi_voxels(xml_file, pet_dir, roi_name = "Tumour")
  rad = pyradiomics_features(x, pet_dir, python = python)
  expect_equal(rad$check[["mask_voxels"]], nrow(x$voxels))
  expect_lt(rad$check[["max_z_distance"]], 0.01)
  expect_lt(rad$check[["max_suv_difference"]], 1e-8)
  f = setNames(rad$features$value, rad$features$feature)
  expect_equal(f[["original_firstorder_Maximum"]], max(x$voxels$suv))
  expect_equal(f[["original_firstorder_Mean"]], mean(x$voxels$suv))
  expect_equal(f[["original_shape_VoxelVolume"]], nrow(x$voxels) * 4 * 4 * 3.27, tolerance = 0.01)
})
